#include <unistd.h>

int	main(int argc, char *argv[])
{
	int	i;
	int	b;

	if (argc > 1)
	{
		i = argc - 1;
		while (i > 0)
		{
			b = 0;
			while (argv[i][b] != '\0')
			{
				write (1, &argv[i][b], 1);
				b++;
			}
			write (1, "\n", 1);
			i--;
		}
	}
	return (0);
}
