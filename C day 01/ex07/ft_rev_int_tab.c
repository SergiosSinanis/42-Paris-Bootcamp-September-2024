void	ft_rev_int_tab(int *tab, int size)
{
	int	i;
	int	b;
	int	c;

	i = 0;
	b = size - 1;
	while (i < b)
	{
		c = tab[i];
		tab[i] = tab[b];
		tab[b] = c;
		i++;
		b--;
	}
}
